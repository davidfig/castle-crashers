/** Every character the story font can draw (plus the space). */
export const STORY_CHARS = ' ' + Object.keys(STORY_GLYPHS).join('');

/** Width of each glyph: its widest row (lowercase glyphs start with blank rows). */
const WIDTHS: Record<string, number> = Object.fromEntries(Object.entries(STORY_GLYPHS).map(([k, rows]) => [k, Math.max(...rows.map((r) => r.length))]));

export function glyphWidth(ch: string): number {
  if (ch === ' ') return SPACE_W;
  return WIDTHS[ch] ?? WIDTHS['?'];
}

/** Width in pixels of `text` at 1x. */
export function storyWidth(text: string): number {
  let w = 0;
  for (const ch of text) w += glyphWidth(ch) + 1;
  return Math.max(0, w - 1);
}

/** Text with anything the font cannot draw turned into something it can: curly quotes and dashes, and the rest into '?'. */
export function storySafe(text: string): string {
  return text
    .replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[–—]/g, '-').replace(/…/g, '...')
    .replace(/[^ -~]/g, '?')
    .split('').map((ch) => (ch === ' ' || STORY_GLYPHS[ch] ? ch : '?')).join('');
}
