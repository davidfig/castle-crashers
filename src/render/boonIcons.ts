type Pix = { w: number; h: number; rgba: Uint8ClampedArray };

/** Build the 16x16 badge for symbol `id` from palette `pal` (palette key -> 0xRRGGBB; 'k' is the lead outline). */
export function boonPixels(sym: BoonSymbol, pal: Readonly<Record<string, number>>): Pix {
  const N = BOON_SIZE;
  const rgba = new Uint8ClampedArray(N * N * 4);
  const put = (x: number, y: number, c: number): void => {
    const o = (y * N + x) * 4;
    rgba[o] = (c >> 16) & 255; rgba[o + 1] = (c >> 8) & 255; rgba[o + 2] = c & 255; rgba[o + 3] = 255;
  };
  const [rim, fill] = THEMES[sym.theme];
  const lead = pal.k, c = (N - 1) / 2;
  for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) {
    const dx = x - c, dy = y - c, d = Math.sqrt(dx * dx + dy * dy);
    if (d > 7.6) continue;
    if (d > 6.7) put(x, y, lead);
    else if (d > 5.6 && dx + dy < 2) put(x, y, pal[rim]); // the lit rim: upper-left only
    else put(x, y, sym.theme === 'ink' ? pal.ink : pal[fill]);
  }
  const rows = sym.rows.map((r) => (sym.mirror ? r + [...r].reverse().join('') : r));
  for (let y = 0; y < SYM; y++) for (let x = 0; x < SYM; x++) {
    const ch = rows[y]?.[x] ?? '.';
    if (ch !== '.' && pal[ch] !== undefined) put(3 + x, 3 + y, pal[ch]);
  }
  return { w: N, h: N, rgba };
}
