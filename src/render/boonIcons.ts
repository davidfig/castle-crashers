// The upgrade pictures (docs/04, docs/13): one 16x16 badge per upgrade, so a level-up card, the camp, the merchant and the HUD can
// show what a boon IS at a glance. Each is a round enamel badge (a themed disc with a lead outline and a lit rim) with a 10x10
// symbol drawn on it in the Glass palette. Procedural text bitmaps like the rest of the UI kit, packed into the atlas at startup
// (uiArt.ts), so a drawn replacement can slot in under the same `boon-<id>` name. A symbol marked `mirror` gives its left five
// columns and is reflected.
